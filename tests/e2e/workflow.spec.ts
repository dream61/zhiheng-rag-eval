 const auth=await request.post(base+'token/',{data:credentials});expect(auth.ok()).toBeTruthy();
 const {token}=await auth.json();const headers={Authorization:'Token '+token};
 async function post(path:string,data:unknown){const r=await request.post(base+path,{headers,data});expect(r.ok(),await r.text()).toBeTruthy();return r.json()}
 const kb=await post('assets/',{kind:'knowledge',name:'界面测试知识库',product:'界面测试产品',version:'1',content:[{name:'手册.md',text:'已发货订单不支持取消。'}]});
