 const sample={id:'ui-001',question:'已发货订单能取消吗？',reference:'不支持取消',type:'订单状态',should_refuse:false,approved:false,required:['不支持取消'],evidence:[{document:'手册.md',text:'已发货订单不支持取消。'}]};
 const ds=await post('assets/',{kind:'dataset',name:'界面测试数据集',product:'界面测试产品',version:'1',content:[sample]});
 const regression=await post('assets/',{kind:'dataset',name:'界面测试回归集',product:'界面测试产品',version:'1',content:[]});
 await page.goto('/');await page.getByLabel('用户名').fill(credentials.username);await page.getByLabel('密码',{exact:true}).fill(credentials.password);await page.getByRole('button',{name:'登录',exact:true}).click();
 await expect(page.getByRole('button',{name:'退出登录'})).toBeVisible();
 await page.getByRole('button',{name:'评测数据集',exact:true}).click();
 await page.getByRole('row').filter({hasText:'界面测试数据集'}).getByRole('button',{name:'编辑与审核'}).click();
