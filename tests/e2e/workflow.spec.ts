 await expect(page.getByText('复核已保存，原始评分已保留')).toBeVisible();
 await page.getByLabel('目标回归数据集').selectOption(String(regression.id));await page.getByLabel('加入原因').fill('验证失败回归');await page.getByLabel('预期修复条件').fill('明确不支持取消');await page.getByRole('button',{name:'加入回归集',exact:true}).click();
